def _runtime_model_middleware(state_schema: type):
    """Use the caller-supplied adapter for a native LangChain agent."""

    @wrap_model_call(state_schema=state_schema)
    def runtime_model(
        request: ModelRequest,
        handler: Callable[[ModelRequest], ModelResponse],
    ) -> ModelResponse:
        adapter = request.runtime.context["model"]
        model = getattr(adapter, "model", None)
        if not isinstance(model, BaseChatModel):
            raise TypeError("native agent requires ModelAdapter.model to be a BaseChatModel")
        model_settings = {
            **dict(getattr(adapter, "bind_tools_kwargs", {})),
            **request.model_settings,
        }
        response = handler(request.override(model=model, model_settings=model_settings))
        invalid = next(
            (
                message
                for message in response.result
                if isinstance(message, AIMessage) and message.invalid_tool_calls
            ),
            None,
        )
        if invalid is not None:
            raise InvalidToolCallFailure(invalid)
        return response

    return runtime_model


