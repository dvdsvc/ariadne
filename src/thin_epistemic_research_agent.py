def _build_researcher_agent(
    technical_tools: Sequence[TechnicalTool],
    registered_data_sources: Sequence[RegisteredDataSourceDescription],
):
    """Build R as LangChain's native ReAct agent graph."""

    tools = list(technical_tools)
    tool_names = {
        str(convert_to_openai_tool(item)["function"]["name"])
        for item in tools
    }
    data_source_catalogue = copy.deepcopy(list(registered_data_sources))

    @dynamic_prompt
    def researcher_context(request: ModelRequest) -> str:
        constitution = request.state.get("constitution")
        return (
            RESEARCHER_PROMPT
            + "\n\nThe current technical task is the latest D-issued HumanMessage."
            + "\n\nConstitution:\n"
            + _json(constitution)
            + "\n\nRegistered data sources:\n"
            + _json(data_source_catalogue)
        )

    @after_agent(state_schema=ResearcherAgentState)
    def seal_technical_packet(
        state: ResearcherAgentState,
        _: Runtime[RuntimeContext],
    ) -> dict[str, Any]:
        task = state["technical_task"]
        task_history = _current_task_history(
            state["messages"],
            task["task_id"],
        )
        tool_call_ids = list(
            dict.fromkeys(
                str(message.tool_call_id)
                for message in task_history
                if isinstance(message, ToolMessage)
                and message.tool_call_id
                and str(message.name or "") in tool_names
                and not _is_control_interruption(message)
            )
        )
        if not tool_call_ids:
            raise ValueError("R must use at least one registered technical tool")

        structured = state.get("structured_response")
        if hasattr(structured, "model_dump"):
            structured = structured.model_dump()
        if not isinstance(structured, dict):
            raise TypeError("R finished without structured TechnicalResults")
        results = [
            str(item).strip()
            for item in structured.get("results", [])
            if str(item).strip()
        ]
        if not results:
            raise ValueError("R must return at least one obtained technical result")

        packet_digest = hashlib.sha256(
            _json(
                {
                    "task_id": task["task_id"],
                    "results": results,
                    "tool_call_ids": tool_call_ids,
                }
            ).encode("utf-8")
        ).hexdigest()[:16]
        packet: TechnicalPacket = {
            "packet_id": f"packet-{packet_digest}",
            "task_id": task["task_id"],
            "item_id": task["item_id"],
            "results": results,
            "tool_call_ids": tool_call_ids,
        }
        return {
            "technical_packet": packet,
            "evidence_ledger": [packet],
            "archive_index": [
                {
                    "archive_id": f"packet:{packet['packet_id']}",
                    "entry_kind": "technical_packet",
                    "item_id": packet["item_id"],
                    "task_id": packet["task_id"],
                    "reference_id": packet["packet_id"],
                }
            ],
        }

    return create_agent(
        _RuntimeModelPlaceholder(),
        tools=tools,
        middleware=[
            researcher_context,
            _native_model_retry(),
            _researcher_runtime_model_middleware(),
            _researcher_repetition_guard_middleware(),
            seal_technical_packet,
        ],
        response_format=ToolStrategy(TechnicalResults),
        state_schema=ResearcherAgentState,
        context_schema=RuntimeContext,
        name="researcher",
    )


def _build_department_agent(
    technical_tools: Sequence[TechnicalTool],
    researcher_agent: Any,
):
    """Build D as a native agent whose delegation tool runs one complete R episode."""

    capability_envelope = _r_capability_envelope(technical_tools)
    capability_catalogue = _r_capability_catalogue(technical_tools)

    @tool(
        "capability__query",
        description=(
            "Return R's compact capability catalogue when the default capability "
            "summary is insufficient. This inspects capability only; it performs no work."
        ),
    )
    def query_capability(capability_question: str) -> JSON:
        """Inspect R's capability surface only when D is uncertain about feasibility."""

        return {
            "capability_question": capability_question,
            "capabilities": copy.deepcopy(capability_catalogue),
        }

    @tool(
        "delegate_to_researcher",
        description=(
            "Delegate one direction-open technical question. One call runs a complete "
            "multi-step R tool loop and returns one TechnicalPacket."
        ),
    )
    def delegate_to_researcher(
        technical_question: str,
        depends_on_previous_results: Annotated[
            bool,
            "Whether answering this question requires intermediate results from the immediately preceding R work.",
        ],
        runtime: ToolRuntime[Any, DepartmentAgentState],
    ) -> Command:
        """Run a complete R episode while keeping R's tool messages out of D history."""

        selected_package = runtime.state.get("selected_item_package")
        if not isinstance(selected_package, dict) or not isinstance(
            selected_package.get("item"), dict
        ):
            raise ValueError("D delegation requires P's selected epistemic item")
        item_id = str(selected_package["item"]["item_id"])
        question = str(technical_question).strip()
        if not question:
            raise ValueError("D delegation requires a non-empty technical question")
        if not runtime.tool_call_id:
            raise ValueError("D delegation requires a tool_call_id")
        task_digest = hashlib.sha256(
            _json(
                {
                    "item_id": item_id,
                    "technical_question": question,
                    "tool_call_id": runtime.tool_call_id,
                }
            ).encode("utf-8")
        ).hexdigest()[:16]
        task: TechnicalTask = {
            "task_id": f"task-{task_digest}",
            "item_id": item_id,
            "technical_question": question,
        }
        prior_r_messages = (
            _project_researcher_messages(
                runtime.state.get("researcher_messages", [])
            )
            if depends_on_previous_results
            else []
        )
        task_message = HumanMessage(
            id=f"technical-task:{task['task_id']}",
            content=_json({"technical_task": task}),
        )
        researcher_result = researcher_agent.invoke(
            {
                "messages": [*prior_r_messages, task_message],
                "constitution": runtime.state["constitution"],
                "technical_task": task,
                "objective_ledger": list(runtime.state.get("objective_ledger", [])),
                "evidence_ledger": list(runtime.state.get("evidence_ledger", [])),
                "report_ledger": list(runtime.state.get("report_ledger", [])),
                "archive_index": list(runtime.state.get("archive_index", [])),
                "technical_packet": None,
            },
            config=runtime.config,
            context=runtime.context,
        )
        packet = researcher_result.get("technical_packet")
        if not isinstance(packet, dict):
            raise TypeError("R episode finished without a TechnicalPacket")
        retained_r_messages = _project_researcher_messages(
            researcher_result.get("messages", []),
            completed_packet=cast(TechnicalPacket, packet),
        )
        return Command(
            update={
                "messages": [
                    ToolMessage(
                        content=_json({"technical_packet": packet}),
                        name="delegate_to_researcher",
                        tool_call_id=runtime.tool_call_id,
                    )
                ],
                "researcher_messages": [
                    RemoveMessage(id=REMOVE_ALL_MESSAGES),
                    *retained_r_messages,
                ],
                "technical_task": task,
                "technical_packet": packet,
                "objective_ledger": list(
                    researcher_result.get("objective_ledger", [])
                ),
                "evidence_ledger": list(researcher_result.get("evidence_ledger", [])),
                "report_ledger": list(researcher_result.get("report_ledger", [])),
                "archive_index": list(researcher_result.get("archive_index", [])),
            }
        )

    @dynamic_prompt
    def department_context(request: ModelRequest) -> str:
        constitution = request.state.get("constitution")
        selected_package = request.state.get("selected_item_package")
        projected = _project_constitution_reference(
            cast(JSON, selected_package),
            cast(InquiryConstitution, constitution),
            owner="P-selected local epistemic package",
        )
        return (
            DEPARTMENT_PROMPT
            + "\n\nConstitution:\n"
            + _json(constitution)
            + "\n\nSelected epistemic item:\n"
            + _json(projected)
            + "\n\nR capability envelope:\n"
            + _json(capability_envelope)
        )

    @after_agent(state_schema=DepartmentAgentState)
    def seal_department_report(
        state: DepartmentAgentState,
        _: Runtime[RuntimeContext],
    ) -> dict[str, Any]:
        selected_package = state["selected_item_package"]
        item_id = str(selected_package["item"]["item_id"])
        structured = state.get("structured_response")
        if hasattr(structured, "model_dump"):
            structured = structured.model_dump()
        if not isinstance(structured, dict):
            raise TypeError("D finished without structured DepartmentResults")
        report_digest = hashlib.sha256(
            _json({"item_id": item_id, "results": structured}).encode("utf-8")
        ).hexdigest()[:16]
        report = cast(
            DepartmentReport,
            {
                "report_id": f"report-{report_digest}",
                "item_id": item_id,
                **structured,
            },
        )
        return {
            "department_report": report,
            "report_ledger": [report],
            "archive_index": [
                {
                    "archive_id": f"report:{report['report_id']}",
                    "entry_kind": "department_report",
                    "item_id": report["item_id"],
                    "task_id": "",
                    "reference_id": report["report_id"],
                }
            ],
        }

    return create_agent(
        _RuntimeModelPlaceholder(),
        tools=[query_capability, delegate_to_researcher],
        middleware=[
            department_context,
            _native_model_retry(),
            _runtime_model_middleware(DepartmentAgentState),
            seal_department_report,
        ],
        response_format=ToolStrategy(DepartmentResults),
        state_schema=DepartmentAgentState,
        context_schema=RuntimeContext,
        name="department",
    )


def build_graph(
    technical_tools: Sequence[TechnicalTool],
    *,
    checkpointer: BaseCheckpointSaver,
    registered_data_sources: Sequence[RegisteredDataSourceDescription] = (),
):
    """Compile the role graph with nested native LangChain D and R agents."""

    researcher_agent = _build_researcher_agent(
        technical_tools,
        registered_data_sources,
    )
    department_agent = _build_department_agent(technical_tools, researcher_agent)

    def interpretation_node(
        state: InterpretationInput,
        runtime: Runtime[RuntimeContext],
    ) -> dict[str, Any]:
        output = _structured(
            runtime.context["model"],
            InterpretationOutput,
            INTERPRETATION_PROMPT,
            {"question": state["question"]},
        )
        extracted = output["constitution"]
        constitution: InquiryConstitution = {
            "question": state["question"],
            "research_object": extracted["research_object"],
            "boundaries": list(extracted["boundaries"]),
            "requested_output": extracted["requested_output"],
        }
        return {
            "constitution": constitution,
            "u_snapshot": None,
            "selected_item_package": None,
            "technical_task": None,
            "messages": [],
            "researcher_messages": [],
            "objective_ledger": [],
            "evidence_ledger": [],
            "report_ledger": [],
            "archive_index": [],
            "technical_packet": None,
            "department_report": None,
        }

    def planner_node(
        state: PlannerInput,
        runtime: Runtime[RuntimeContext],
    ) -> dict[str, Any]:
        snapshot = state["u_snapshot"]
        selection = _structured(
            runtime.context["model"],
            PlannerSelection,
            PLANNER_PROMPT,
            {
                "constitution": state["constitution"],
                "u_snapshot": _project_constitution_reference(
                    cast(JSON, snapshot),
                    state["constitution"],
                    owner="U snapshot",
                ),
            },
        )
        selected_id = str(selection["selected_item_id"])
        selected = next(
            (
                item
                for item in snapshot["epistemic_map"]["items"]
                if item["item_id"] == selected_id and item["status"] == "open"
            ),
            None,
        )
        if selected is None:
            raise ValueError("P must select one open item_id from U's epistemic map")
        return {
            "selected_item_package": _materialize_local_epistemic_package(
                snapshot, selected
            ),
            "technical_task": None,
            "technical_packet": None,
            "department_report": None,
            "messages": [
                HumanMessage(
                    id=(
                        f"department-item:{snapshot['epistemic_map']['revision']}:"
                        f"{selected_id}"
                    ),
                    content=_json({"selected_epistemic_item_id": selected_id}),
                )
            ],
        }

    def updater_node(
        state: UpdaterInput,
        runtime: Runtime[RuntimeContext],
    ) -> dict[str, Any]:
        prior = state.get("u_snapshot")
        if prior is None:
            context = {
                "mode": "bootstrap",
                "constitution": state["constitution"],
            }
            prompt = UPDATER_BOOTSTRAP_PROMPT
            old_revision = None
        else:
            report = state.get("department_report")
            if report is None:
                raise ValueError("U revision requires a formal DepartmentReport")
            context = {
                "mode": "revise",
                "constitution": state["constitution"],
                "current_u_snapshot": _project_constitution_reference(
                    cast(JSON, prior),
                    state["constitution"],
                    owner="current U snapshot",
                ),
                "department_report": report,
            }
            prompt = UPDATER_PROMPT
            old_revision = int(prior["epistemic_map"]["revision"])
        update = _structured(
            runtime.context["model"],
            UpdaterOutput,
            prompt,
            context,
        )
        output = cast(
            EpistemicSnapshot,
            {
                "constitution": state["constitution"] if prior is None else prior["constitution"],
                **update,
            },
        )
        new_revision = int(output["epistemic_map"]["revision"])
        if old_revision is None:
            if new_revision != 0:
                raise ValueError("U bootstrap must publish revision 0")
        elif new_revision <= old_revision:
            raise ValueError("U must advance the epistemic map revision")
        item_ids = [item["item_id"] for item in output["epistemic_map"]["items"]]
        if not item_ids or len(item_ids) != len(set(item_ids)):
            raise ValueError("U must publish non-empty epistemic items with unique item_id values")
        open_items = [
            item
            for item in output["epistemic_map"]["items"]
            if item["status"] == "open"
        ]
        update_decision = output["decision"]
        if update_decision == "close" and open_items:
            raise ValueError("U cannot close while an epistemic item remains open")
        if update_decision in {"continue", "restructure"} and not open_items:
            raise ValueError(
                f"U decision={update_decision} requires at least one open epistemic item"
            )
        return {
            "u_snapshot": output,
            "selected_item_package": None,
            "technical_task": None,
            "messages": [RemoveMessage(id=REMOVE_ALL_MESSAGES)] if prior else [],
            "researcher_messages": (
                [RemoveMessage(id=REMOVE_ALL_MESSAGES)] if prior else []
            ),
            "technical_packet": None,
            "department_report": None,
        }

    def writer_node(
        state: WriterInput,
        runtime: Runtime[RuntimeContext],
    ) -> dict[str, Any]:
        output = _structured(
            runtime.context["model"],
            WriterOutput,
            WRITER_PROMPT,
            {
                "constitution": state["constitution"],
                "u_snapshot": _project_constitution_reference(
                    cast(JSON, state["u_snapshot"]),
                    state["constitution"],
                    owner="publication U snapshot",
                ),
            },
        )
        return {"final_answer": output["answer"]}

    def route_after_planner(state: PlannerRouteInput) -> Literal["department"]:
        package = state.get("selected_item_package")
        if package is None:
            raise ValueError("P did not select an epistemic item")
        return "department"

    def route_after_updater(state: PlannerInput) -> Literal["planner", "writer"]:
        decision = state["u_snapshot"]["decision"]
        return "writer" if decision == "close" else "planner"

    builder = StateGraph(
        DeepResearchState,
        context_schema=RuntimeContext,
        input_schema=ResearchInput,
        output_schema=ResearchOutput,
    )
    builder.add_node(
        "interpretation",
        interpretation_node,
        input_schema=InterpretationInput,
        retry_policy=MODEL_RETRY_POLICY,
    )
    builder.add_node(
        "planner",
        planner_node,
        input_schema=PlannerInput,
        retry_policy=MODEL_RETRY_POLICY,
    )
    builder.add_node(
        "department",
        department_agent,
    )
    builder.add_node(
        "updater",
        updater_node,
        input_schema=UpdaterInput,
        retry_policy=MODEL_RETRY_POLICY,
    )
    builder.add_node(
        "writer",
        writer_node,
        input_schema=WriterInput,
        retry_policy=MODEL_RETRY_POLICY,
    )

    builder.add_edge(START, "interpretation")
    builder.add_edge("interpretation", "updater")
    builder.add_conditional_edges(
        "planner",
        route_after_planner,
        {"department": "department"},
    )
    builder.add_edge("department", "updater")
    builder.add_conditional_edges(
        "updater",
        route_after_updater,
        {"planner": "planner", "writer": "writer"},
    )
    builder.add_edge("writer", END)
    return builder.compile(checkpointer=checkpointer)


