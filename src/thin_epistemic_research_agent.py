def _r_capability_envelope(
    technical_tools: Sequence[TechnicalTool],
) -> RCapabilityEnvelope:
    """Summarize R's live capability surface without exposing tool cards."""

    has_table_gateway = False
    has_scientific_tools = False

    for technical_tool in technical_tools:
        metadata = getattr(technical_tool, "metadata", None)
        metadata = metadata if isinstance(metadata, dict) else {}
        tool_schema = convert_to_openai_tool(technical_tool)["function"]
        tool_name = str(tool_schema.get("name") or "")
        native_tool_id = str(metadata.get("native_tool_id") or "")
        if native_tool_id == "data.tool" or tool_name == "data__tool":
            has_table_gateway = True
        elif str(metadata.get("capability_group") or "") != "execution_archive":
            has_scientific_tools = True

    capabilities: list[str] = []
    if has_table_gateway:
        capabilities.append(
            "read registered tables and execute read-only SQL-style data operations"
        )
    if has_scientific_tools:
        capabilities.append(
            "perform mathematical or statistical computation with registered tools"
        )
    if not capabilities:
        return {"summary": "R has no registered technical capability for new work."}
    return {
        "summary": "R can "
        + " and ".join(capabilities)
        + ". It can combine multiple tool calls within one technical task."
    }


def _r_capability_catalogue(
    technical_tools: Sequence[TechnicalTool],
) -> list[JSON]:
    """Build D's optional compact capability view without exposing tool schemas."""

    grouped: dict[str, JSON] = {}
    for technical_tool in technical_tools:
        metadata = getattr(technical_tool, "metadata", None)
        metadata = metadata if isinstance(metadata, dict) else {}
        function = convert_to_openai_tool(technical_tool)["function"]
        group = str(
            metadata.get("capability_group")
            or metadata.get("native_tool_id")
            or function.get("name")
            or "technical_operation"
        )
        card = grouped.setdefault(
            group,
            {
                "capability": group,
                "description": str(function.get("description") or ""),
                "accepts": [],
                "produces": [],
                "requires": [],
            },
        )
        for target, source in (
            ("accepts", "input_objects"),
            ("produces", "output_objects"),
            ("requires", "hard_requirements"),
        ):
            values = metadata.get(source, [])
            if not isinstance(values, list):
                continue
            card[target] = list(
                dict.fromkeys([*card[target], *(str(value) for value in values)])
            )
    return list(grouped.values())


def _current_task_history(
    messages: Sequence[AnyMessage],
    task_id: str,
) -> list[AnyMessage]:
    """Return messages after the durable boundary for the current D-issued task."""

    marker_id = f"technical-task:{task_id}"
    for index in range(len(messages) - 1, -1, -1):
        message = messages[index]
        if isinstance(message, HumanMessage) and message.id == marker_id:
            return list(messages[index + 1 :])
    raise ValueError(f"technical message history has no boundary for task {task_id}")


_HASH_DEDUPLICATED_TOOL_KEYS = frozenset({"request", "provenance"})
_VOLATILE_EXECUTION_KEYS = frozenset(
    {"id", "local_intent", "objective_record_id", "result_id", "tool_call_id"}
)
_NON_BEHAVIORAL_ACTION_KEYS = frozenset({"local_intent"})
_CONSECUTIVE_DUPLICATE_ACTION_LIMIT = 3
_CONTROL_INTERRUPTION_KEY = "control_interruption"


def _deduplicate_tool_json(value: Any) -> Any:
    """Replace repeated request/provenance objects with content-addressed references."""

    seen: dict[str, tuple[str, str]] = {}

    def visit(item: Any, path: str, owner_key: str | None = None) -> Any:
        if isinstance(item, (dict, list)) and owner_key in _HASH_DEDUPLICATED_TOOL_KEYS:
            canonical = json.dumps(
                item,
                ensure_ascii=False,
                sort_keys=True,
                separators=(",", ":"),
                default=str,
            )
            digest = f"sha256:{hashlib.sha256(canonical.encode('utf-8')).hexdigest()}"
            previous = seen.get(digest)
            if previous is not None and previous[0] == canonical:
                return {"$ref": previous[1], "content_hash": digest}
            seen[digest] = (canonical, path)

        if isinstance(item, dict):
            return {
                str(key): visit(child, f"{path}.{key}", str(key))
                for key, child in item.items()
            }
        if isinstance(item, list):
            return [
                visit(child, f"{path}[{index}]", owner_key)
                for index, child in enumerate(item)
            ]
        return item

    return visit(value, "$")


def _project_tool_content(content: Any) -> Any:
    """Keep tool evidence intact while hash-deduplicating repeated JSON structures."""

    if not isinstance(content, str):
        return content
    try:
        decoded = json.loads(content)
    except (TypeError, ValueError, json.JSONDecodeError):
        return content
    return json.dumps(
        _deduplicate_tool_json(decoded),
        ensure_ascii=False,
        default=str,
    )


def _stable_fingerprint(
    value: Any,
    *,
    ignored_keys: frozenset[str],
) -> tuple[str, Any]:
    """Hash nested JSON-like content after removing the selected keys."""

    def stable(item: Any) -> Any:
        if isinstance(item, dict):
            return {
                str(key): stable(child)
                for key, child in item.items()
                if str(key) not in ignored_keys
            }
        if isinstance(item, list):
            return [stable(child) for child in item]
        return item

    normalized = stable(value)
    canonical = json.dumps(
        normalized,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
        default=str,
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest(), normalized


def _execution_fingerprint(value: Any) -> tuple[str, Any]:
    """Hash execution results after removing per-call runtime identities."""

    return _stable_fingerprint(value, ignored_keys=_VOLATILE_EXECUTION_KEYS)


def _action_fingerprint(tool_name: str, arguments: Any) -> tuple[str, Any]:
    """Hash an actual tool action while ignoring only its narrative intent label."""

    digest, normalized = _stable_fingerprint(
        {"tool": tool_name, "arguments": arguments},
        ignored_keys=_NON_BEHAVIORAL_ACTION_KEYS,
    )
    return digest, normalized["arguments"]


def _is_control_interruption(message: ToolMessage) -> bool:
    """Return whether a ToolMessage records a control refusal, not an execution."""

    return bool(message.additional_kwargs.get(_CONTROL_INTERRUPTION_KEY))


def _completed_researcher_actions(
    messages: Sequence[AnyMessage],
) -> list[tuple[str, str, Any, str]]:
    """Reconstruct completed real tool actions and their stable result identities."""

    pending: dict[str, tuple[str, str, Any]] = {}
    completed: list[tuple[str, str, Any, str]] = []
    for message in messages:
        if isinstance(message, AIMessage):
            for call in message.tool_calls:
                tool_name = str(call.get("name") or "")
                call_id = str(call.get("id") or "")
                if not call_id or tool_name == "TechnicalResults":
                    continue
                action_hash, stable_args = _action_fingerprint(
                    tool_name,
                    call.get("args") or {},
                )
                pending[call_id] = (tool_name, action_hash, stable_args)
            continue
        if not isinstance(message, ToolMessage):
            continue
        call_id = str(message.tool_call_id or "")
        action = pending.pop(call_id, None)
        if action is None or _is_control_interruption(message):
            continue
        if isinstance(message.content, str):
            try:
                result_payload = json.loads(message.content)
            except (TypeError, ValueError, json.JSONDecodeError):
                result_payload = message.content
        else:
            result_payload = message.content
        result_hash, _ = _execution_fingerprint(result_payload)
        completed.append((*action, result_hash))
    return completed


def _repetition_banned_action_hashes(
    messages: Sequence[AnyMessage],
    *,
    limit: int = _CONSECUTIVE_DUPLICATE_ACTION_LIMIT,
) -> set[str]:
    """Find actions that have already reached the consecutive execution limit."""

    banned: set[str] = set()
    previous_hash: str | None = None
    run_length = 0
    for _, action_hash, _, _ in _completed_researcher_actions(messages):
        if action_hash == previous_hash:
            run_length += 1
        else:
            previous_hash = action_hash
            run_length = 1
        if run_length >= limit:
            banned.add(action_hash)
    return banned


def _current_researcher_episode_history(
    messages: Sequence[AnyMessage],
    state: Any,
) -> list[AnyMessage]:
    """Limit execution control to the current D-issued R work line."""

    task = state.get("technical_task") if isinstance(state, dict) else None
    task_id = str(task.get("task_id") or "") if isinstance(task, dict) else ""
    if not task_id:
        return list(messages)
    try:
        return _current_task_history(messages, task_id)
    except ValueError:
        return list(messages)


def _researcher_repetition_observation(
    messages: Sequence[AnyMessage],
) -> JSON | None:
    """Describe a repeated completed action without deciding whether R must stop."""

    completed = _completed_researcher_actions(messages)

    if len(completed) < 2:
        return None
    latest_action_hash = completed[-1][1]
    repeated: list[tuple[str, str, Any, str]] = []
    for action in reversed(completed):
        if action[1] != latest_action_hash:
            break
        repeated.append(action)
    repeated.reverse()
    if len(repeated) < 2:
        return None

    latest_result_changed = repeated[-1][3] != repeated[-2][3]
    return {
        "execution_repetition_observation": {
            "recent_action": {
                "tool": repeated[-1][0],
                "arguments": repeated[-1][2],
            },
            "consecutive_repeat_count": len(repeated),
            "result_changed_across_repeats": len(
                {action[3] for action in repeated}
            )
            > 1,
            "new_information_from_latest_repeat": (
                "result_changed"
                if latest_result_changed
                else "none"
            ),
        }
    }


def _append_repetition_observation(
    system_message: SystemMessage | None,
    observation: JSON | None,
) -> SystemMessage | None:
    """Attach the control-layer observation to R's system context for one call."""

    if observation is None:
        return system_message
    note = (
        "\n\nControl-layer observation of completed execution history:\n"
        + _json(observation)
    )
    if system_message is None:
        return SystemMessage(content=note.lstrip())
    content = system_message.content
    if isinstance(content, str):
        return SystemMessage(content=content + note)
    return SystemMessage(content=[*copy.deepcopy(content), {"type": "text", "text": note}])


def _project_researcher_messages(
    messages: Sequence[AnyMessage],
    *,
    completed_packet: TechnicalPacket | None = None,
) -> list[AnyMessage]:
    """Project R memory without provider metadata, free-form thought, or result acks."""

    technical_result_call_ids = {
        str(call.get("id") or "")
        for message in messages
        if isinstance(message, AIMessage)
        for call in message.tool_calls
        if str(call.get("name") or "") == "TechnicalResults"
        and str(call.get("id") or "")
    }
    projected: list[AnyMessage] = []
    for message in messages:
        if isinstance(message, HumanMessage):
            projected.append(
                HumanMessage(
                    content=copy.deepcopy(message.content),
                    name=message.name,
                    id=message.id,
                )
            )
            continue
        if isinstance(message, AIMessage):
            tool_calls = [
                copy.deepcopy(call)
                for call in message.tool_calls
                if str(call.get("name") or "") != "TechnicalResults"
            ]
            if tool_calls:
                projected.append(
                    AIMessage(
                        content="",
                        name=message.name,
                        tool_calls=tool_calls,
                    )
                )
            continue
        if isinstance(message, ToolMessage):
            if (
                str(message.name or "") == "TechnicalResults"
                or str(message.tool_call_id or "") in technical_result_call_ids
            ):
                continue
            projected.append(
                ToolMessage(
                    content=_project_tool_content(message.content),
                    name=message.name,
                    tool_call_id=message.tool_call_id,
                    status=message.status,
                    artifact=copy.deepcopy(message.artifact),
                )
            )
            continue
        if isinstance(message, SystemMessage):
            projected.append(SystemMessage(content=copy.deepcopy(message.content)))

    if completed_packet is not None:
        projected.append(
            HumanMessage(
                content=_json(
                    {
                        "previous_technical_results": list(
                            completed_packet.get("results", [])
                        )
                    }
                )
            )
        )
    return projected


